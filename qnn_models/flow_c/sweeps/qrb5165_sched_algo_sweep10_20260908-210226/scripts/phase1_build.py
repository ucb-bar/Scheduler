#!/usr/bin/env python3
"""Phase 1a — build every network the ported sweep10 workloads need, as far as
a per-backend QNN context binary on the QRB5165, and record what composed.

The reference experiment (RoSE/experiments/sched_algo_sweep10) targets
`firesim_f2_rocket_saturn` and its networks are thin PyTorch wrapper modules in
modelblaster's own model zoo (models/<net>_s<k>.py, generated by
experiments/workload_gen/mk_scaled_variants.py). Flow C ingests PyTorch through
the same `extract_graph` on the same zoo, so those variants are ingestable here
without inventing new models -- which is the whole reason this replication is
possible.

Two facts govern this script:

  * The scale env var is read at IMPORT time of the backing module, so a
    process can only ever build ONE rung. Every export/extract therefore runs
    in its own subprocess.
  * The /scratch2 modelblaster submodule is pinned at 2026-08-27, which
    predates the `_s*` wrappers (2026-09-03) and fastdepth.py (2026-09-05). The
    zoo used here is therefore the RoSE working tree -- the SAME zoo the
    reference experiment used, which is the fidelity-maximising choice. Nothing
    is written into either tree; the IR and ONNX land under this sweep.

Precision per backend is not a free choice, it is what the backends accept
(measured in qnn_models/opsweep, see its README):

    hta   int8 only  -- a float DLC is rejected with `incorrect Datatype 0x508`
    dsp   int8 only  -- same
    cpu   fp32 here  -- int8-on-CPU is a reference kernel for conv and is
                        NUMERICALLY DEAD for mlp_control (constant output for
                        any input, measurements/qrb5165_v66.json). The int8
                        compose is still attempted and recorded, but the cell
                        this sweep solves against is fp32.
    gpu   fp16       -- the stock qti.aisw GPU package rejects every quantized
                        tensor at GPU_ERROR_INVALID_TYPE(10012) before any
                        op-specific check, so gpu/int8 does not exist.

A (tile, backend) pair that fails to compose is a RESULT, recorded with the
verbatim validator message, not an inconvenience to be worked around. No
offline ONNX rewrite is applied: the reference's networks are taken as the zoo
exports them, so the compose outcome describes those networks and not a
hand-tuned variant of them. (dronet's existing HTA context on this board only
exists because dronet.onnx was BN-rewritten, FC-head-replaced and
trailing-view-dropped offline by ad-hoc scripts that were never committed --
qnn_models/optimization_flow.md marks all three "(ad-hoc)". Reproducing that
per rung would make the scale ladder a ladder of three different graphs.)

    python3 phase1_build.py [--only dronet_sc,fastdepth] [--force] [--skip-board]
"""
